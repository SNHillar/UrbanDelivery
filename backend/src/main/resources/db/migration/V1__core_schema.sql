-- Esquema P0 según docs/04-modelo-er.md §2.
-- deliveries y courier_profiles quedan para una migración posterior, cuando se valide el actor COURIER.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name     VARCHAR(120) NOT NULL,
    phone         VARCHAR(30),
    role          VARCHAR(20)  NOT NULL CHECK (role IN ('CLIENT', 'MERCHANT', 'COURIER', 'ADMIN')),
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE merchants (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id   BIGINT        NOT NULL UNIQUE REFERENCES users (id),
    name            VARCHAR(120)  NOT NULL,
    category        VARCHAR(60),
    address         VARCHAR(255)  NOT NULL,
    phone           VARCHAR(30),
    opening_hours   TEXT,
    offers_pickup   BOOLEAN       NOT NULL DEFAULT TRUE,
    offers_delivery BOOLEAN       NOT NULL DEFAULT FALSE,
    delivery_fee    NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (delivery_fee >= 0),
    approval_status VARCHAR(20)   NOT NULL DEFAULT 'PENDING'
        CHECK (approval_status IN ('PENDING', 'APPROVED', 'REJECTED')),
    approved_by     BIGINT REFERENCES users (id),
    approved_at     TIMESTAMPTZ,
    CONSTRAINT merchants_offers_something CHECK (offers_pickup OR offers_delivery)
);

CREATE TABLE products (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id BIGINT         NOT NULL REFERENCES merchants (id),
    name        VARCHAR(120)   NOT NULL,
    description TEXT,
    price       NUMERIC(10, 2) NOT NULL CHECK (price > 0),
    available   BOOLEAN        NOT NULL DEFAULT TRUE,
    active      BOOLEAN        NOT NULL DEFAULT TRUE
);

CREATE TABLE orders (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id          BIGINT         NOT NULL REFERENCES users (id),
    merchant_id        BIGINT         NOT NULL REFERENCES merchants (id),
    fulfillment_type   VARCHAR(10)    NOT NULL CHECK (fulfillment_type IN ('PICKUP', 'DELIVERY')),
    status             VARCHAR(20)    NOT NULL
        CHECK (status IN ('PENDING', 'PREPARING', 'READY', 'COMPLETED', 'REJECTED', 'CANCELLED')),
    delivery_address   VARCHAR(255),
    delivery_reference VARCHAR(255),
    notes              TEXT,
    subtotal           NUMERIC(10, 2) NOT NULL,
    delivery_fee       NUMERIC(10, 2) NOT NULL,
    total              NUMERIC(10, 2) NOT NULL,
    status_reason      VARCHAR(255),
    created_at         TIMESTAMPTZ    NOT NULL,
    accepted_at        TIMESTAMPTZ,
    ready_at           TIMESTAMPTZ,
    completed_at       TIMESTAMPTZ,
    version            BIGINT         NOT NULL DEFAULT 0,
    -- Invariante #9: DELIVERY tiene dirección; PICKUP no cobra envío
    CONSTRAINT orders_delivery_has_address CHECK (fulfillment_type <> 'DELIVERY' OR delivery_address IS NOT NULL),
    CONSTRAINT orders_pickup_without_fee CHECK (fulfillment_type <> 'PICKUP' OR delivery_fee = 0),
    -- Invariante #10: rechazo con motivo
    CONSTRAINT orders_rejected_has_reason CHECK (status <> 'REJECTED' OR status_reason IS NOT NULL)
);

CREATE TABLE order_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT         NOT NULL REFERENCES orders (id),
    product_id   BIGINT         NOT NULL REFERENCES products (id),
    product_name VARCHAR(120)   NOT NULL,
    unit_price   NUMERIC(10, 2) NOT NULL,
    quantity     INT            NOT NULL CHECK (quantity > 0),
    line_total   NUMERIC(10, 2) NOT NULL
);

CREATE TABLE order_status_history (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT       NOT NULL REFERENCES orders (id),
    entity        VARCHAR(10)  NOT NULL CHECK (entity IN ('ORDER', 'DELIVERY')),
    from_status   VARCHAR(20),
    to_status     VARCHAR(20)  NOT NULL,
    actor_user_id BIGINT REFERENCES users (id),
    reason        VARCHAR(255),
    created_at    TIMESTAMPTZ  NOT NULL
);

CREATE INDEX idx_orders_merchant_status ON orders (merchant_id, status);
CREATE INDEX idx_orders_client_created ON orders (client_id, created_at);
CREATE INDEX idx_order_items_order ON order_items (order_id);
CREATE INDEX idx_history_order_created ON order_status_history (order_id, created_at);
